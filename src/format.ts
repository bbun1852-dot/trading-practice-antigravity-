/**
 * 가격 표기. 자릿수를 가격 규모로 정한다.
 *
 * 고정 2자리는 BTC($71,408)에서는 충분하지만 ADA($0.24)에서는 정보를 통째로 잃는다.
 * 실제로 "종가 1.33 가 직전 스윙로우 1.33 하향 붕괴" 처럼 **감지기 자신의 발화 조건이
 * 두 값의 차이를 보증하는데 화면에는 같은 수가 찍히는** 자기모순이 나왔다.
 *
 * 경계는 실측으로 정했다 (2026-08-09, BTC·ETH·SOL·XRP·LINK·ADA·DOGE × 4h/1d,
 * 평봉을 뺀 14,000봉). 기준은 **"같은 봉의 low 와 high 가 서로 다른 문자열로 찍히는가"** 다 —
 * 감지기가 내놓는 가격 쌍 중 가장 촘촘한 것이 같은 봉의 low/high 라서 이게 최악 조건이다.
 *
 *   버킷      표본     최대 필요   채택   여유
 *   >=1000   4,000     0자리      2      2
 *   >=1      5,668     3자리      4      1
 *   <1       4,332     4자리      6      2
 *
 * 가장 빠듯한 곳은 `>=1` 버킷이다($1 근처의 초저변동 봉). 여유가 1자리뿐이므로,
 * 이 버킷의 자릿수를 줄이려면 반드시 다시 재야 한다.
 *
 * **비율에는 쓰지 않는다.** ATR 배수·R:R·RSI·거래량 배수·밴드폭 % 는 무차원 수라
 * "가격 규모별 자릿수" 라는 개념이 성립하지 않고, 애초에 뭉개지지도 않는다.
 */
export function fmtPrice(v: number): string {
  const a = Math.abs(v)
  if (a >= 1000) return v.toFixed(2)
  if (a >= 1) return v.toFixed(4)
  return v.toFixed(6)
}
